export function className(map: SaveMap, id: number): string {
  return map.classes.find((c) => c.id === id)?.name ?? `Beruf ${id}`;
}

export function raceName(map: SaveMap, id: number): string {
  return map.races.find((r) => r.id === id)?.name ?? (id ? `Rasse ${id}` : "—");
}

export function itemName(id: number): string {
  if (id === 0) return "leer";
  return KNOWN_ITEM_IDS[id] ?? `Item ${id.toString(16).toUpperCase().padStart(4, "0")}`;
}
