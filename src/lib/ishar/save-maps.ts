import type { FieldSpec, SaveMap } from "./types";

function field(
  partial: Omit<FieldSpec, "stride"> & { stride?: number },
): FieldSpec {
  return {
    stride: partial.size === 2 ? 2 : 1,
    min: 0,
    max: partial.size === 2 ? 65535 : 255,
    ...partial,
  };
}

