import {importCont,setGridCell} from '../src/lib/ishar/cont-grid.ts';
import assert from 'node:assert/strict';
import {mkdtemp,mkdir,writeFile,readFile,access} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {createContPatch,createGridContPatch,applyContPatch,sha256} from '../src/lib/ishar/cont-patch.ts';
import {exportContMod} from './cont-mod.mjs';
for(const size of [4860,10800]){
 const original=Uint8Array.from({length:size},(_,i)=>i%256),target=original.slice(),before=original.slice();
 target[0]=99;target[size-1]=50;
 const patch=await createContPatch(original,target,'CONT1.FIC');
 const parsed=importCont(original,'CONT1.FIC',await sha256(original));assert.ok(parsed.ok);
 const editorGrid=setGridCell(parsed.grid,'A',0,0,99);
 const editorPatch=await createGridContPatch(editorGrid,original);
 assert.equal(editorPatch.edits.length,1,'editor snapshot patch');
 await assert.rejects(createGridContPatch({...editorGrid,source:undefined},original),/Originalquelle/);
 await assert.rejects(createGridContPatch({...editorGrid,rows:1},original),/Abmessungen/);
 const other=original.slice();other[10]^=1;
 await assert.rejects(createGridContPatch(editorGrid,other),/Originalquelle/);
 assert.equal(patch.game,size===4860?'ishar1':'ishar2');assert.equal(patch.edits.length,2);
 assert.deepEqual(await applyContPatch(original,JSON.parse(JSON.stringify(patch))),target);
 assert.deepEqual(await createContPatch(original,target,'CONT1.FIC'),patch,'deterministic patch');
 assert.deepEqual(await applyContPatch(original,await createContPatch(original,original,'CONT1.FIC')),original,'no-op');
 assert.deepEqual(original,before,'input not mutated');
 const invalid=structuredClone(patch);invalid.edits[0].before=222;
 await assert.rejects(applyContPatch(original,invalid),/Before-byte/);
 for(const value of [null,{}, {...patch,version:2},{...patch,game:'ishar3'}, {...patch,resource:'../CONT1.FIC'}, {...patch,sourceSha256:'0'.repeat(64)},{...patch,targetSha256:'0'.repeat(64)}, {...patch,game:size===4860?'ishar2':'ishar1'}])await assert.rejects(applyContPatch(original,value));
 for(const edit of [{...patch.edits[0],row:1000},{...patch.edits[0],col:-1},{...patch.edits[0],row:0.5},{...patch.edits[0],after:256},{...patch.edits[0],layer:'C'},...(size===4860?[{...patch.edits[0],layer:'B'}]:[])])await assert.rejects(applyContPatch(original,{...patch,edits:[edit]}));
 await assert.rejects(applyContPatch(original,{...patch,edits:[patch.edits[0],patch.edits[0]]}),/Duplicate/);
 await assert.rejects(createContPatch(original,new Uint8Array(100),'CONT1.FIC'));
}
const base=await mkdtemp(join(tmpdir(),'ishar-cont-mod-')),root=join(base,'original'),output=join(base,'copy');
await mkdir(root);const source=new Uint8Array(4860),target=source.slice();target[12]=7;
await writeFile(join(root,'CONT1.FIC'),source);await writeFile(join(root,'UNKNOWN.DAT'),Buffer.from([1,4,9]));
const patch=await createContPatch(source,target,'CONT1.FIC');
await assert.rejects(exportContMod(root,patch,join(root,'bad')),/separate/);
await assert.rejects(access(join(root,'bad')),'rejected path must not be created');
await assert.rejects(exportContMod(root,{...patch,sourceSha256:'0'.repeat(64)},join(base,'bad')),/SHA-256 mismatch/);
await assert.rejects(access(join(base,'bad')),'invalid patch must not create output');
const report=await exportContMod(root,patch,output);
assert.equal(report.verification,'prepared-not-tested-in-original');
assert.deepEqual(new Uint8Array(await readFile(join(root,'CONT1.FIC'))),source);
assert.deepEqual(new Uint8Array(await readFile(join(output,'CONT1.FIC'))),target);
assert.deepEqual(await readFile(join(output,'UNKNOWN.DAT')),await readFile(join(root,'UNKNOWN.DAT')));
await assert.rejects(exportContMod(root,patch,output),/already exists/);
assert.equal(JSON.parse(await readFile(join(output,'ishar-ck-mod-manifest.json'),'utf8')).patch.targetSha256,await sha256(target));
console.log('Both CONT profiles: deterministic patches, hash binding, malformed-edit rejection, source protection, clone/readback and unknown-byte preservation passed.');
