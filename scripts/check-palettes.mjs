import assert from 'node:assert/strict';
import { resolveIshar2Palettes } from '../src/lib/ishar/palette-resolution.ts';
const palette = (sourcePath,entryIndex,firstColor,colorCount,value) => ({sourcePath,entryIndex,firstColor,colorCount,palette:new Uint8Array(768).fill(value)});
const image = (sourcePath,entryIndex) => ({sourcePath,entryIndex,palette:new Uint8Array(768).fill(255),pixels:Uint8Array.of(150,151),paletteSource:'default'});
const base=palette('game/FOND1.IO',3,0,256,10);
const dungeon=palette('game/FDJ1.IO',2,0,256,30);
const actor=palette('game/GUARD3.IO',22,160,16,70);
const night=palette('game/GUARD3.IO',23,160,16,2);
const obsolete=palette('game/MAIN.IO',11,0,256,255);
const images=[image('game/DJ1.IO',13),image('game/GUARD3.IO',2),image('game/OBJET.IO',69)];
const pixels=images.map(i=>i.pixels.slice());
const result=resolveIshar2Palettes(images,[obsolete,night,dungeon,base,actor]);
assert.equal(images[0].palette[90],30,'Dungeon uses paired scene palette');
assert.equal(images[1].palette[160*3],70,'Actor palette after the image is applied');
assert.equal(images[1].palette[0],10,'Partial overlay preserves scene base');
assert.equal(images[1].palette[176*3],10,'Partial overlay ends at its declared range');
assert.equal(images[2].palette[0],10,'MAIN placeholder palette is never a scene fallback');
assert.equal(result.localCount,1);assert.equal(result.globalCount,2);
images.forEach((i,n)=>assert.deepEqual(i.pixels,pixels[n],'Indexed source pixels unchanged'));
assert.equal(base.palette[160*3],10,'Shared palette is not mutated');
assert.match(images[2].paletteLabel,/Szenenkontext offen/);
const noBase=image('GUARD3.IO',2);
resolveIshar2Palettes([noBase],[{...actor,sourcePath:'GUARD3.IO'}]);
assert.equal(noBase.palette[160*3],70,'Module-only import resolves its local bank');
const red=palette('RED.IO',9,128,16,0); for(let i=128;i<144;i++)red.palette[i*3]=255;
const fire=image('RED.IO',0);resolveIshar2Palettes([fire],[base,red]);
assert.deepEqual([...fire.palette.slice(128*3,128*3+3)],[255,0,0],'Genuine red stays red');
console.log('Palette resolution regression tests passed');
