import assert from 'node:assert/strict';
import {mkdtemp,mkdir,writeFile,readFile} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {inventoryInstallation,writeInventory} from './inventory-originals.mjs';
const test=await mkdtemp(join(tmpdir(),'ishar-inventory-')),root=join(test,'original'),out=join(test,'reports');
await mkdir(root);await writeFile(join(root,'START.EXE'),new Uint8Array([77,90,1,2]));
await writeFile(join(root,'UNKNOWN.BIN'),new Uint8Array([0,255,7]));
const first=await inventoryInstallation(root,'ishar1'),second=await inventoryInstallation(root,'ishar1');
assert.deepEqual(first,second,'deterministic ordering and metadata');
assert.equal(first.fileCount,2);assert.equal(first.files[0].executableSignature,'MZ');
assert.equal(first.files[1].sha256.length,64);assert.equal(first.language,'unverified');
await assert.rejects(writeInventory([{root,game:'ishar1'}],join(root,'output')),/outside original/);
await writeInventory([{root,game:'ishar1'}],out);await writeInventory([{root,game:'ishar1'}],out);
assert.deepEqual(await readFile(join(root,'UNKNOWN.BIN')),Buffer.from([0,255,7]));
await writeFile(join(out,'ishar1-inventory.json'),'do not overwrite');
await assert.rejects(writeInventory([{root,game:'ishar1'}],out),error=>error.code==='EEXIST');
console.log('Inventory determinism, signatures, hash metadata, source protection and overwrite protection passed.');
