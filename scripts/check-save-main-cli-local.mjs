import assert from 'node:assert/strict';
import {readFileSync,writeFileSync,mkdtempSync,existsSync} from 'node:fs';
import {join} from 'node:path';
import {tmpdir} from 'node:os';
import {execFileSync,spawnSync} from 'node:child_process';
import {deriveIshar2SaveLayout,readIshar2SavedMain} from '../src/lib/ishar/ishar2-save-layout.ts';
import {originalNpcGoldTransfer} from '../src/lib/ishar/original-npc-gold.ts';
const root=process.env.ISHAR2_DIR;if(!root)throw Error('ISHAR2_DIR required');
const io=join(root,'IO.IO'),save=join(root,'START.SAV'),original=new Uint8Array(readFileSync(save)),layout=await deriveIshar2SaveLayout(new Uint8Array(readFileSync(io)));
const memory=readIshar2SavedMain(original,layout),trace=originalNpcGoldTransfer(memory,0,53,[0,1]);
const dir=mkdtempSync(join(tmpdir(),'ishar-save-main-')),writes=join(dir,'writes.json'),output=join(dir,'modified.SAV');writeFileSync(writes,JSON.stringify(trace.operations));
const args=['scripts/save-main.mjs','patch',io,save,writes,output];
const report=JSON.parse(execFileSync(process.execPath,args,{encoding:'utf8'}));assert.ok(report.changedOffsets.length);assert.equal(report.fieldCount,141);
const back=readIshar2SavedMain(new Uint8Array(readFileSync(output)),layout);
for(const op of trace.operations)assert.equal(op.width===1?back.get(op.address):(back.get(op.address)<<8)|back.get(op.address+1),op.value&(op.width===1?255:65535));
assert.notEqual(spawnSync(process.execPath,args).status,0,'no overwrite');
const forbidden=join(root,'codex-must-not-write.SAV');assert.equal(existsSync(forbidden),false);
assert.notEqual(spawnSync(process.execPath,[...args.slice(0,-1),forbidden]).status,0,'original directory rejected');assert.equal(existsSync(forbidden),false);
assert.deepEqual(new Uint8Array(readFileSync(save)),original);
console.log(`CLI NPC gold trace exported and read back; overwrite/source directory rejected; original unchanged. Private test files retained at ${dir}`);
