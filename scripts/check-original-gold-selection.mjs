import assert from 'node:assert/strict';
import {beginOriginalGoldSelection,originalGoldSelectionInput as step,selectAllOriginalGold} from '../src/lib/ishar/original-gold-selection.ts';
const inc={button:1,x:190,y:90},dec={button:1,x:225,y:90},balance=[10,0];
let state=beginOriginalGoldSelection(0);
for(let i=0;i<25;i++)state=step(state,balance,inc).state;
assert.deepEqual(state,{gold:[0,25],step:1,repeatCounter:25});
state=step(state,balance,inc).state;assert.deepEqual(state,{gold:[0,26],step:10,repeatCounter:1},'26th accepted action adds old step, then accelerates');
for(let i=0;i<25;i++)state=step(state,balance,inc).state;
assert.deepEqual(state,{gold:[0,276],step:100,repeatCounter:1});
state=step(state,balance,{button:0,x:190,y:90}).state;assert.deepEqual(state,{gold:[0,276],step:1,repeatCounter:0},'release resets repeat/step, not selected gold');
assert.equal(step(state,balance,{button:2,x:0,y:0}).action,'exit');
assert.deepEqual(step(beginOriginalGoldSelection(0),[0,0],inc).state,beginOriginalGoldSelection(0),'upper bound rejects instead of clamping');
const old={gold:[0,5],step:10,repeatCounter:12};assert.deepEqual(step(old,balance,dec).state,{gold:[0,5],step:10,repeatCounter:13},'failed debit still advances repeat after nonnegative test');
assert.deepEqual(old,{gold:[0,5],step:10,repeatCounter:12},'input state immutable');
assert.deepEqual(step({gold:[1,0],step:1,repeatCounter:0},balance,dec).state.gold,[0,999]);
for(const x of [183,195,220,256])assert.equal(step(beginOriginalGoldSelection(0),balance,{...inc,x}).accepted,false);
for(const y of [82,99,114,115])assert.equal(step(beginOriginalGoldSelection(0),balance,{...inc,y}).accepted,false);
assert.equal(step(beginOriginalGoldSelection(0),balance,{...inc,x:232}).action,'exit');
assert.equal(step(beginOriginalGoldSelection(0),balance,{...inc,y:98}).accepted,true);
assert.deepEqual(selectAllOriginalGold(old,[5,999]),{...old,gold:[5,999]});
assert.equal(beginOriginalGoldSelection(25).repeatCounter,25,'entry preserves explicit transient counter');
assert.throws(()=>beginOriginalGoldSelection(undefined));
console.log('Original gold selection bounds, exact button rectangles, repeat acceleration, release/exit, failed-debit behavior, select-all and transient-state requirements passed.');
