import assert from 'node:assert/strict';
import { buyFromNpc, stockKey } from '../src/lib/ishar/trading.ts';
import { reconcileItemPlacements, instantiateLocationItems } from '../src/lib/ishar/item-instances.ts';
import { starterGame, normalizeGame } from '../src/lib/ishar/project.ts';
import { validateGame } from '../src/lib/ishar/project-validation.ts';
const before=['key','rune','key'], placements=['a','b','c'];
assert.deepEqual(reconcileItemPlacements(before,placements,['rune','key','key']),['b','a','c']);
assert.deepEqual(reconcileItemPlacements(before,placements,['rune','key']),['b','a']);
assert.deepEqual(reconcileItemPlacements(before,placements,['new','key'],()=> 'fresh'),['fresh','a']);
const game=normalizeGame(starterGame());
game.locations[0].itemIds=['sun-key','crypt-rune'];game.locations[0].itemPlacementIds=['a','b'];
const original=instantiateLocationItems(game).locations[0].itemIds[1];
game.locations[0].itemPlacementIds=reconcileItemPlacements(game.locations[0].itemIds,game.locations[0].itemPlacementIds,['crypt-rune']);
game.locations[0].itemIds=['crypt-rune'];
assert.equal(instantiateLocationItems(game).locations[0].itemIds[0],original,'Removing another item keeps copy identity');
assert.deepEqual(normalizeGame(JSON.parse(JSON.stringify(game))),game,'Placement IDs survive project round trip');
const npc={id:'merchant',name:'Test',dialogue:'Hello',stock:[{itemId:'sun-key',price:7,quantity:2}]};
const state={gold:20,remaining:{},purchased:[]};
const one=buyFromNpc(state,npc,0,'hero',0,()=> 'first');
assert.equal(one.ok,true);assert.equal(one.state.gold,13);assert.equal(one.state.remaining[stockKey(npc.id,0)],1);
const two=buyFromNpc(one.state,npc,0,'hero',1,()=> 'second');
assert.equal(two.ok,true);assert.equal(two.state.gold,6);assert.notEqual(one.purchase.id,two.purchase.id);
assert.equal(buyFromNpc(two.state,npc,0,'hero',2,()=>{throw Error('sold out must not allocate')}).ok,false);
assert.equal(buyFromNpc({...state,gold:6},npc,0,'hero',0,()=>{throw Error('poor must not allocate')}).ok,false);
assert.equal(buyFromNpc(state,npc,0,'hero',9,()=>{throw Error('full must not allocate')}).ok,false);
assert.deepEqual(state,{gold:20,remaining:{},purchased:[]},'Rejected and accepted trades never mutate input');
game.npcs=[npc];game.locations[0].npcIds=[npc.id];
assert.equal(validateGame(game).length,0);
game.npcs[0].stock[0].quantity=-1;assert.ok(validateGame(game).some(p=>p.path.includes('stock')));
console.log('Stable ground identities, NPC placement and atomic purchases passed');
