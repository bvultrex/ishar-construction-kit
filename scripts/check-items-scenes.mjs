import assert from 'node:assert/strict';
import { starterGame } from '../src/lib/ishar/project.ts';
import { instantiateLocationItems, inventoryHasDefinition } from '../src/lib/ishar/item-instances.ts';
import { inferIrvanScene, irvanSceneAfterStep } from '../src/lib/ishar/scene-state.ts';
import { sceneTypeAt } from '../src/lib/ishar/grid-view.ts';
const authored=starterGame();
const definition=authored.items[0];
authored.locations[0].itemIds=[definition.id,definition.id];
authored.locations[1].itemIds=[definition.id];
const before=JSON.stringify(authored), runtime=instantiateLocationItems(authored);
assert.equal(JSON.stringify(authored),before,'runtime instancing never rewrites authored data');
const ids=[...runtime.locations[0].itemIds,...runtime.locations[1].itemIds];
assert.equal(new Set(ids).size,3,'same definition, three independent placements');
assert.deepEqual(instantiateLocationItems(authored),runtime,'IDs remain stable across rebuilds');
assert.deepEqual(instantiateLocationItems(runtime),runtime,'instancing is idempotent');
assert.ok(inventoryHasDefinition(runtime,[ids[0]],definition.id),'instanced keys retain their door definition');
assert.equal(runtime.locations[1].itemIds.filter(id=>![ids[0]].includes(id)).length,1,'collecting one copy leaves another on the ground');
assert.equal(inventoryHasDefinition(runtime,[],definition.id),false);
assert.equal(irvanSceneAfterStep(41,32,4),5);
assert.equal(irvanSceneAfterStep(40,32,5),4);
assert.equal(irvanSceneAfterStep(79,39,5),9);
assert.equal(irvanSceneAfterStep(78,38,9),9,'original strict thresholds');
assert.equal(irvanSceneAfterStep(77,38,9),5);
assert.equal(irvanSceneAfterStep(24,20,6),7);
assert.equal(irvanSceneAfterStep(23,20,7),6);
assert.equal(inferIrvanScene(50,32),5);
assert.equal(inferIrvanScene(10,27),2);
assert.equal(sceneTypeAt({game:'ishar2',rows:1,cols:1,layerA:'AA==',mapNumber:1},0,0,6),6,'saved scene state takes precedence');
console.log('Independent item copies, key identity, stable IDs and Irvan scene transitions passed.');
