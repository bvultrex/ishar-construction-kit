import assert from 'node:assert/strict';
import {authoredItemsInSight,originalStarterItem,originalItemResource} from '../src/lib/ishar/authored-item-view.ts';
const rune=originalStarterItem({id:'placed-rune',definitionId:'crypt-rune',name:'Runenstein',description:''});
assert.equal(rune.id,'placed-rune');assert.equal(rune.originalObjectCode,9);
assert.deepEqual([0,1,2].map(d=>originalItemResource(rune,d)),[115,116,117]);
assert.deepEqual([0,1,2].map(d=>originalItemResource({name:'Schlüssel',description:''},d)),[69,70,71]);
assert.equal(originalItemResource(rune,3),undefined);
const locations=[0,1,2].map(i=>({id:`cell${i}`,x:0,y:-i,itemIds:i===2?['key']:[],exits:[`cell${i-1}`,`cell${i+1}`]}));
const game={locations,doors:[{id:'door',fromLocationId:'cell0',toLocationId:'cell1'}]};
assert.deepEqual(authoredItemsInSight(game,locations[0],'north',[],[]),[],'closed door occludes item');
assert.deepEqual(authoredItemsInSight(game,locations[0],'north',['door'],[]),[{id:'key',depth:2}],'open door reveals far sprite');
assert.deepEqual(authoredItemsInSight(game,locations[0],'north',['door'],['key']),[],'picked item does not reappear at distance');
game.doors[0].originalIndex=1;
assert.deepEqual(authoredItemsInSight(game,locations[0],'north',[],[]),[{id:'key',depth:2}],'closed grate permits sight');
game.doors[0].originalIndex=0;
assert.deepEqual(authoredItemsInSight(game,locations[0],'north',[],[]),[],'closed wooden door blocks sight');
assert.deepEqual(authoredItemsInSight(game,locations[1],'north',[],[]),[{id:'key',depth:1}]);
locations[1].exits=[];
assert.deepEqual(authoredItemsInSight(game,locations[0],'north',['door'],[]),[],'wall terminates sight');
console.log('Original replacement resources and item visibility through open/closed doors passed.');
