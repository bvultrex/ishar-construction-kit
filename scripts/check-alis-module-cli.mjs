import assert from 'node:assert/strict';
import {execFileSync} from 'node:child_process';
import {mkdtemp,mkdir,writeFile,readFile,access} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {packSilmA1} from '../src/lib/ishar/silm-write.ts';
import {readAlisModule} from '../src/lib/ishar/alis-module.ts';
const base=await mkdtemp(join(tmpdir(),'alis-module-cli-')),root=join(base,'original'),out=join(base,'output');await mkdir(root);await mkdir(out);
const image=new Uint8Array(32),view=new DataView(image.buffer);view.setUint16(0,4,true);view.setUint16(2,22,true);view.setUint32(14,26,true);image[31]=55;
const packed=packSilmA1(image),source=join(root,'TEST.IO');await writeFile(source,packed);
const cli=(...args)=>JSON.parse(execFileSync(process.execPath,['scripts/alis-module.mjs',...args],{encoding:'utf8',stdio:['ignore','pipe','pipe']}));
assert.equal(cli('inspect',source).header.id,4);
const exported=join(out,'image.bin');cli('extract',source,exported);assert.deepEqual(new Uint8Array(await readFile(exported)),image);
assert.throws(()=>cli('extract',source,join(root,'bad.bin')));await assert.rejects(access(join(root,'bad.bin')));
const changed=image.slice();changed[31]=99;const edited=join(out,'edited.bin');await writeFile(edited,changed);
const target=join(out,'TEST.IO'),report=cli('replace-image',source,edited,target);assert.ok(report.verification.includes('not tested'));
assert.deepEqual(readAlisModule(new Uint8Array(await readFile(target))).image,changed);
assert.deepEqual(new Uint8Array(await readFile(source)),packed,'source stays unchanged');
assert.throws(()=>cli('replace-image',source,edited,target),'existing output must not be overwritten');
await writeFile(join(out,'short.bin'),new Uint8Array(30));assert.throws(()=>cli('replace-image',source,join(out,'short.bin'),join(out,'bad.IO')));await assert.rejects(access(join(out,'bad.IO')));
console.log('ALIS inspect/extract/replace CLI: full file readback, source/output guards and invalid-size rejection passed.');
